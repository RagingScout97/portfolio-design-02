/**
 * Exports a hand-picked subset of game-icons.net (CC BY 3.0) into a typed
 * path-data module. Emitting markup instead of .svg files keeps the icons
 * inheriting `currentColor`, so they can be tinted and animated by CSS.
 *
 * Run: node scripts/export-game-icons.mjs
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { getIconData, iconToSVG } from "@iconify/utils";

const require = createRequire(import.meta.url);
const iconSet = require("@iconify-json/game-icons/icons.json");

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_FILE = resolve(ROOT, "src/components/icons/generated/paths.ts");

/** Keep this list tight — every entry ships in the client bundle. */
const WANTED = [
  // main menu
  "scroll-unfurled",
  "crossed-swords",
  "family-tree",
  "treasure-map",
  "joystick",
  "crystal-ball",
  // chrome and decor
  "torch",
  "fire-bowl",
  "candle-flame",
  "castle",
  "lion",
  "dungeon-gate",
  "stone-tower",
  "rune-stone",
  "crystal-shine",
  "key",
  "crown",
  "shield",
  "spell-book",
  "open-book",
  "broadsword",
  "wizard-staff",
  "skills",
  "anvil",
  "locked-chest",
  "health-potion",
  "on-target",
  "round-star",
  "cog",
  "laptop",
];

const missing = WANTED.filter((name) => !iconSet.icons[name]);
if (missing.length) {
  console.error(
    `Missing from game-icons set: ${missing.join(", ")}\n` +
      "Search available names with: node -e \"console.log(Object.keys(require('@iconify-json/game-icons/icons.json').icons).filter(n=>n.includes('QUERY')))\"",
  );
  process.exit(1);
}

const entries = WANTED.map((name) => {
  const data = getIconData(iconSet, name);
  const { body, attributes } = iconToSVG(data, { height: "none" });
  const viewBox = attributes.viewBox ?? "0 0 512 512";
  return { name, body: body.replace(/\s+/g, " ").trim(), viewBox };
});

const union = entries.map((e) => `  | "${e.name}"`).join("\n");
const records = entries
  .map(
    (e) =>
      `  "${e.name}": {\n    viewBox: "${e.viewBox}",\n    body: ${JSON.stringify(e.body)},\n  },`,
  )
  .join("\n");

const out = `// GENERATED by scripts/export-game-icons.mjs — do not edit by hand.
// Source: game-icons.net by Lorc, Delapouite & contributors (CC BY 3.0).

export type GameIconName =
${union};

export const GAME_ICONS: Record<
  GameIconName,
  { viewBox: string; body: string }
> = {
${records}
};
`;

mkdirSync(dirname(OUT_FILE), { recursive: true });
writeFileSync(OUT_FILE, out, "utf8");
console.log(`Wrote ${entries.length} icons to ${OUT_FILE}`);
